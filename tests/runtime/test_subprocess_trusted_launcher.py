def test_launcher_policy_in_forbidden_directory_is_rejected(tmp_path: Path):
    """Launcher rejects policy from bundle, output, scratch with 125 (goal.md §6.2)."""
    launcher_py = Path(__file__).resolve().parent.parent.parent / "src" / "vibereview" / "runtime" / "trusted_launcher.py"

    # Create dummy policy in scratch/
    scratch_dir = tmp_path / "scratch"
    scratch_dir.mkdir()
    bad_policy = scratch_dir / "launcher_policy.json"
    bad_policy.write_text("{}", encoding="utf-8")
    report = tmp_path / "report.json"

    cmd = [
        sys.executable,
        str(launcher_py),
        "--policy",
        str(bad_policy),
        "--report",
        str(report),
        "--",
        sys.executable,
        "-c",
        "print('hello')",
    ]
    res = subprocess.run(cmd, capture_output=True, text=True)
    assert res.returncode == 125
    assert "policy" in res.stderr.lower()


def test_launcher_exit_125_fails_closed_as_internal_runtime_failure(tmp_path: Path):
    """Launcher failure before launch maps to INTERNAL_RUNTIME_FAILURE without fallback (goal.md §6.5)."""
    class Exit125Engine(SubprocessEngine):
        def _run(self, session, credentials, started):
            launcher = session.launcher_dir / "trusted_launcher.py"
            launcher.chmod(0o700)
            launcher.write_text(
                "import sys; sys.exit(125)\n", encoding="utf-8"
            )
            return super()._run(session, credentials, started)

    runtime_bad = ProjectRuntime.create(tmp_path / "project_bad", project_name="bad-launcher")
    engine_bad = Exit125Engine(
        name="bad-launcher-engine",
        worker_script=WORKER,
        modes=("valid",),
        proposal_payloads={
            "valid_proposal.json": json.dumps(VALID_PROPOSAL).encode("utf-8")
        },
    )
    result = _run_task(runtime_bad, engine_bad)

    assert result.outcome is AttemptOutcome.INTERNAL_RUNTIME_FAILURE
    record = result.attempt_records[0]
    assert any(f.code == "launcher_setrlimit_failed" for f in record.detected_failures)


def test_applied_limits_model_and_distinction():
    """Verify RLIMIT_NPROC and RLIMIT_AS are defense-in-depth/non-authoritative (goal.md §6.4)."""
    policy_dict = {
        "max_open_files": 512,
        "max_processes": 32,
        "max_address_space_bytes": 1024 * 1024 * 1024,
    }
    records = apply_limits(policy_dict)
    models = [AppliedResourceLimit.model_validate(r) for r in records]

    by_code = {m.code: m for m in models}
    if ResourceLimitCode.MAX_OPEN_FILES in by_code:
        assert by_code[ResourceLimitCode.MAX_OPEN_FILES].authoritative is True
    if ResourceLimitCode.MAX_PROCESS_COUNT in by_code:
        assert by_code[ResourceLimitCode.MAX_PROCESS_COUNT].authoritative is False
    if ResourceLimitCode.MAX_ADDRESS_SPACE in by_code:
        assert by_code[ResourceLimitCode.MAX_ADDRESS_SPACE].authoritative is False
