def _engine(
    name: str,
    *,
    modes: tuple[str, ...] = ("valid",),
    policy: SubprocessPolicy | None = None,
    launcher_policy: LauncherPolicy | None = None,
    worker_config: dict | None = None,
) -> SubprocessEngine:
    return SubprocessEngine(
        name=name,
        worker_script=WORKER,
        modes=modes,
        policy=policy,
        launcher_policy=launcher_policy,
        worker_config=worker_config,
        proposal_payloads={
            "valid_proposal.json": json.dumps(VALID_PROPOSAL).encode("utf-8")
        },
    )


def _init_runtime(tmp_path: Path) -> ProjectRuntime:
    project_dir = tmp_path / "project"
    return ProjectRuntime.create(project_dir, project_name="launcher-test")


def _run_task(runtime: ProjectRuntime, engine: SubprocessEngine):
    return runtime.run(
        TaskType.GENERATE_CANDIDATE_CLAIMS,
        GenerateCandidateClaimsInvocation(topic="Additive manufacturing", existing_theme_ids=[]),
        engines=[engine],
    )


def test_trusted_launcher_applies_nofile_and_probe_reads_it(tmp_path: Path):
    """Probe inside child reads expected RLIMIT_NOFILE (goal.md §6.6)."""
    policy = deterministic_test_policy().model_copy(
        update={"max_open_files": 256}
    )
    engine = _engine("fake-nofile", modes=("rlimit_nofile_probe", "valid"), policy=policy)
    runtime = _init_runtime(tmp_path)
    result = _run_task(runtime, engine)

    assert result.outcome is AttemptOutcome.VALID_SCIENTIFIC_RESULT
    record = result.attempt_records[0]
    agent_result_path = runtime.project_root / record.agent_result_path
    agent_result = SubprocessAgentResult.model_validate_json(
        agent_result_path.read_text(encoding="utf-8")
    )
    stdout = agent_result.stdout
    assert "RLIMIT_NOFILE=" in stdout
    soft_str = stdout.split("RLIMIT_NOFILE=")[1].split(",")[0].strip()
    assert int(soft_str) == 256

    # Verify applied_limits report in execution_report
    report = agent_result.execution_report
    applied_codes = {item.code: item for item in report.applied_limits}
    assert ResourceLimitCode.MAX_OPEN_FILES in applied_codes
    nofile_record = applied_codes[ResourceLimitCode.MAX_OPEN_FILES]
    assert nofile_record.requested_value == 256
    assert nofile_record.applied_soft_value == 256
    assert nofile_record.supported is True
    assert nofile_record.authoritative is True


def test_trusted_launcher_preserves_explicit_inheritable_executable_fd(
    tmp_path: Path,
) -> None:
    launcher_dir = tmp_path / "launcher"
    launcher_dir.mkdir()
    policy_path = launcher_dir / "launcher_policy.json"
    report_path = launcher_dir / "applied_limits.json"
    policy_path.write_text("{}\n", encoding="utf-8")
    executable_fd = os.open("/bin/true", os.O_RDONLY)
    try:
        os.set_inheritable(executable_fd, True)
        completed = subprocess.run(
            [
                sys.executable,
                str(Path(__file__).resolve().parents[2] / "src/vibereview/runtime/trusted_launcher.py"),
                "--policy", str(policy_path),
                "--report", str(report_path),
                "--", f"/proc/self/fd/{executable_fd}",
            ],
            pass_fds=(executable_fd,),
            capture_output=True,
            text=True,
            timeout=5,
        )
    finally:
        os.close(executable_fd)
    assert completed.returncode == 0, completed.stderr
    assert report_path.is_file()


def test_cpu_spin_reaches_limit_and_attributable_failure(tmp_path: Path):
    """CPU spin reaches configured limit -> attributable resource limit failure (goal.md §6.6)."""
    policy = deterministic_test_policy().model_copy(
        update={"max_cpu_seconds": 1, "timeout_seconds": 15.0}
    )
    engine = _engine("fake-cpu-spin", modes=("cpu_spin",), policy=policy)
    runtime = _init_runtime(tmp_path)
    result = _run_task(runtime, engine)

    assert result.outcome is AttemptOutcome.ENGINE_RESOURCE_LIMIT_FAILURE
    record = result.attempt_records[0]
    assert any(
        f.code == ResourceLimitCode.MAX_CPU_TIME.value for f in record.detected_failures
    )


