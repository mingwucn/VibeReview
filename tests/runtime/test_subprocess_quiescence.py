def test_quiescence_inspection_fails_internally(tmp_path: Path):
    runtime = ProjectRuntime.create(tmp_path / "project", project_name="test")
    engine = _engine(
        "quiesce-fails",
        modes=("valid",),
        execution_root_parent=tmp_path / "exec-roots",
    )
    fallback = _engine("fallback", modes=("valid",), execution_root_parent=tmp_path / "exec-roots")

    with patch(
        "vibereview.runtime.execution.count_process_group_members",
        side_effect=OSError("procfs simulated failure"),
    ):
        result = _run(runtime, engine, fallback_engine=fallback)

    # Must be INTERNAL_RUNTIME_FAILURE, no fallback invoked!
    assert result.outcome is AttemptOutcome.INTERNAL_RUNTIME_FAILURE
    assert len(result.attempt_records) == 1
    record = result.attempt_records[0]
    assert record.outcome is AttemptOutcome.INTERNAL_RUNTIME_FAILURE
    failure_codes = {f.code for f in record.detected_failures}
    assert "quiescence_inspection_failed" in failure_codes


