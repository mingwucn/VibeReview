def test_extra_resource_with_consistent_manifest_entry_is_still_detected(tmp_path):
    runtime, document = _runtime_with_document(tmp_path)
    added = "input/resources/RES0002/content.md"

    def add(task, call_number):
        workspace = task.workspace_dir
        target = workspace / added
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text("# smuggled resource\n", encoding="utf-8")
        manifest_path = workspace / "bundle_manifest.json"
        manifest_path.chmod(0o644)
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        manifest["resources"].append(
            {
                "resource_id": "RES0002",
                "logical_name": "smuggled.md",
                "path": added,
                "media_type": "text/markdown",
                "size_bytes": target.stat().st_size,
                "sha256": hash_file(target),
            }
        )
        manifest_path.write_text(
            json.dumps(manifest, ensure_ascii=False, sort_keys=True, indent=2) + "\n",
            encoding="utf-8",
        )

    forger = _engine("forger", on_execute=add)
    result = _run(runtime, document, forger)

    assert result.outcome is AttemptOutcome.ENGINE_WORKSPACE_INTEGRITY_FAILURE
    errors = "\n".join(result.attempt_records[0].validation_errors)
    assert "extra" in errors
    assert added in errors
    assert "bundle_manifest.json" in errors

    task_dir = runtime.project_root / "work" / "tasks" / result.task_id
    workspace = _workspace(runtime, result.task_id, "01-forger")
    # The augmented manifest is self-consistent, yet the private expected set
    # still convicts the addition.
    assert _manifest_self_consistency_errors(workspace) == []
    with pytest.raises(BundleIntegrityError):
        runtime.tasks.verify_workspace(task_dir, workspace)
    runtime.tasks.verify_bundle(task_dir)


