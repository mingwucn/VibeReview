PRE_EXECUTION_TARGETS = [
    "bundle_manifest.json",
    "input/input.json",
    "contracts/input.schema.json",
    "input/resources/RES0001/content.md",
]


@pytest.mark.parametrize("target", PRE_EXECUTION_TARGETS)
def test_pre_execution_master_bundle_corruption_is_internal_failure(
    tmp_path, monkeypatch, target
):
    runtime, document = _runtime_with_document(tmp_path)
    original_create = runtime.tasks.create

    def corrupting_create(**kwargs):
        task_dir, manifest, provenance = original_create(**kwargs)
        path = task_dir / "bundle" / target
        path.chmod(0o644)
        path.write_text("corrupted before execution\n", encoding="utf-8")
        return task_dir, manifest, provenance

    monkeypatch.setattr(runtime.tasks, "create", corrupting_create)
    primary = _engine("primary")
    fallback = _engine("fallback")
    result = _run(runtime, document, primary, fallback)

    assert result.outcome is AttemptOutcome.INTERNAL_RUNTIME_FAILURE
    assert result.generation is None
    assert result.engine is None
    assert result.attempt_records == []
    assert primary.calls == 0
    assert fallback.calls == 0
    task_dir = runtime.project_root / "work" / "tasks" / result.task_id
    assert list((task_dir / "attempts").iterdir()) == []
    with pytest.raises(BundleIntegrityError):
        runtime.tasks.verify_bundle(task_dir)


def test_pre_execution_workspace_copy_corruption_is_internal_failure(
    tmp_path, monkeypatch
):
    runtime, document = _runtime_with_document(tmp_path)
    original_next_attempt = runtime.tasks.next_attempt

    def corrupting_next_attempt(task_dir, engine_name, task_type):
        attempt_dir, agent_task, attempt_id = original_next_attempt(
            task_dir, engine_name, task_type
        )
        target = agent_task.workspace_dir / "input" / "input.json"
        target.chmod(0o644)
        target.write_text("corrupted copy\n", encoding="utf-8")
        return attempt_dir, agent_task, attempt_id

    monkeypatch.setattr(runtime.tasks, "next_attempt", corrupting_next_attempt)
    primary = _engine("primary")
    fallback = _engine("fallback")
    result = _run(runtime, document, primary, fallback)

    assert result.outcome is AttemptOutcome.INTERNAL_RUNTIME_FAILURE
    assert result.generation is None
    assert result.engine is None
    assert result.attempt_records == []
    assert primary.calls == 0
    assert fallback.calls == 0

    task_dir = runtime.project_root / "work" / "tasks" / result.task_id
    # The master template is intact: only the fresh attempt copy was corrupt.
    runtime.tasks.verify_bundle(task_dir)
    attempt_dir = task_dir / "attempts" / "01-primary"
    assert attempt_dir.is_dir()
    assert not (attempt_dir / "attempt_record.json").exists()
    assert not (attempt_dir / "agent_result.json").exists()


def test_private_trust_anchor_is_never_copied_into_attempt_workspaces(tmp_path):
    runtime, document = _runtime_with_document(tmp_path)

    def tamper(task, call_number):
        path = task.workspace_dir / "instructions.md"
        path.chmod(0o644)
        path.write_text("tampered by primary\n", encoding="utf-8")

    observed: dict[str, object] = {}

    def inspect(task, call_number):
        observed["task"] = task

    primary = _engine("primary", on_execute=tamper)
    fallback = _engine("fallback", on_execute=inspect)
    result = _run(runtime, document, primary, fallback)

    assert result.outcome is AttemptOutcome.VALID_SCIENTIFIC_RESULT
    assert [record.outcome for record in result.attempt_records] == [
        AttemptOutcome.ENGINE_WORKSPACE_INTEGRITY_FAILURE,
        AttemptOutcome.VALID_SCIENTIFIC_RESULT,
    ]

    task_dir = runtime.project_root / "work" / "tasks" / result.task_id
    anchor = task_dir / "private" / "task_provenance.json"
    assert anchor.is_file()

    # The engine-facing handle never points at private/.
    task = observed["task"]
    for field in (
        task.workspace_dir,
        task.instructions_path,
        task.input_dir,
        task.attempt_dir,
    ):
        assert "private" not in field.parts

    private_names = {
        "task_provenance.json",
        "invocation.json",
        "resource_sources.json",
    }
    provenance_keys = ("expected_bundle_manifest_hash", "expected_immutable_files")
    attempt_dirs = sorted((task_dir / "attempts").iterdir())
    assert [path.name for path in attempt_dirs] == ["01-primary", "02-fallback"]
    for attempt_dir in attempt_dirs:
        workspace = attempt_dir / "workspace"
        for path in workspace.rglob("*"):
            relative = path.relative_to(workspace)
            assert "private" not in relative.parts
            assert path.name not in private_names
            if path.is_file() and not path.is_symlink():
                text = path.read_text(encoding="utf-8")
                for key in provenance_keys:
                    assert key not in text

    # The clean fallback workspace is exactly the master bundle: nothing from
    # private/ was added and nothing from bundle/ was lost.
    master = task_dir / "bundle"
    fallback_workspace = _workspace(runtime, result.task_id, "02-fallback")
    master_files = {
        path.relative_to(master).as_posix()
        for path in master.rglob("*")
        if path.is_file()
    }
    fallback_files = {
        path.relative_to(fallback_workspace).as_posix()
        for path in fallback_workspace.rglob("*")
        if path.is_file()
    }
    assert fallback_files == master_files
