@pytest.mark.parametrize(
    ("response", "expected"),
    [
        (
            MockResponse(execution_error="engine unavailable"),
            AttemptOutcome.ENGINE_EXECUTION_FAILURE,
        ),
        (
            MockResponse(raw_output="not-json"),
            AttemptOutcome.ENGINE_FORMAT_FAILURE,
        ),
        (
            MockResponse(proposal={"themes": "wrong", "claims": []}),
            AttemptOutcome.ENGINE_SCHEMA_FAILURE,
        ),
        (
            MockResponse(
                proposal={
                    "themes": [],
                    "claims": [
                        {
                            "local_ref": "claim_1",
                            "theme_ref": "unknown_theme",
                            "candidate_claim": "Claim",
                            "origin": "generated",
                            "origin_refs": [],
                        }
                    ],
                }
            ),
            AttemptOutcome.ENGINE_PROPOSAL_VALIDATION_FAILURE,
        ),
    ],
)
def test_engine_attributable_failures_allow_fallback(tmp_path, response, expected):
    runtime = _create_empty_runtime(tmp_path)
    primary = MockEngine([response], name="primary")
    valid = _positive_proposal("fallback")
    fallback = MockEngine(
        [MockResponse(proposal=valid.model_dump(mode="json"))], name="fallback"
    )
    result = runtime.run(
        TaskType.GENERATE_CANDIDATE_CLAIMS,
        GenerateCandidateClaimsInput(topic="stress", existing_theme_ids=[]),
        dependency_ids=[],
        engines=[primary, fallback],
    )
    assert result.outcome is AttemptOutcome.VALID_SCIENTIFIC_RESULT
    assert [record.outcome for record in result.attempt_records] == [
        expected,
        AttemptOutcome.VALID_SCIENTIFIC_RESULT,
    ]
    assert primary.calls == 1
    assert fallback.calls == 1


