def _positive_proposal(label: str = "theme") -> DiscoveryProposalBundle:
    return DiscoveryProposalBundle(
        themes=[
            ThemeProposal(
                local_ref=f"{label}_1",
                title="Thermal management",
                description="Generated by deterministic fixture",
                origin="generated",
            )
        ],
        claims=[
            CandidateClaimProposal(
                local_ref=f"{label}_claim_1",
                theme_ref=f"{label}_1",
                candidate_claim="Preheating changes residual stress.",
                origin="generated",
                origin_refs=[],
            )
        ],
    )


def _create_empty_runtime(tmp_path, config=None) -> ProjectRuntime:
    return ProjectRuntime.create(
        tmp_path / "project",
        project_name="test",
        config=config,
    )


def _snapshot_without_downstream_claim_objects(bundle_factory) -> RepositorySnapshot:
    bundle = bundle_factory()
    for name in (
        "claim_assessments",
        "final_claim_validations",
        "claim_packets",
        "proposition_records",
        "semantic_audits",
        "rendered_sentences",
        "rendered_sentence_audits",
    ):
        bundle[name] = []
    return RepositorySnapshot.model_validate(bundle)


def _snapshot_ready_for_proposition_audit(bundle_factory) -> RepositorySnapshot:
    bundle = bundle_factory()
    bundle["rendered_sentences"] = []
    bundle["rendered_sentence_audits"] = []
    return RepositorySnapshot.model_validate(bundle)


def test_mock_engine_positive_result_is_canonicalized_and_advances(tmp_path):
    runtime = _create_empty_runtime(tmp_path)
    proposal = _positive_proposal()
    engine = MockEngine([MockResponse(proposal=proposal.model_dump(mode="json"))])
    result = runtime.run(
        TaskType.GENERATE_CANDIDATE_CLAIMS,
        GenerateCandidateClaimsInput(topic="stress", existing_theme_ids=[]),
        dependency_ids=[],
        engines=[engine],
    )
    assert result.outcome is AttemptOutcome.VALID_SCIENTIFIC_RESULT
    assert result.transition is not None
    assert result.transition.canonicalized
    assert result.transition.downstream_eligible
    assert result.generation == 1
    assert result.allocated_ids == {"theme_1": "T0001", "theme_claim_1": "C0001"}
    _, snapshot, _ = runtime.store.load_current()
    assert snapshot.candidate_claims[0].claim_id == "C0001"
    task_dir = runtime.project_root / "work" / "tasks" / result.task_id
    assert (task_dir / "task_manifest.json").is_file()
    assert (task_dir / "accepted" / "proposal.json").is_file()
    assert (task_dir / "attempts" / "01-mock" / "attempt_record.json").is_file()


