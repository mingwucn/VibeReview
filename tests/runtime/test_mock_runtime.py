def test_valid_reject_is_canonicalized_without_fallback_or_claim_packet(
    tmp_path, bundle_factory
):
    snapshot = _snapshot_without_downstream_claim_objects(bundle_factory)
    runtime = ProjectRuntime.create(
        tmp_path / "project", project_name="reject", initial_snapshot=snapshot
    )
    proposal = ClaimAssessmentProposal(
        claim_ref="C0001",
        aggregate_strength="low",
        evidence_sufficiency="insufficient",
        decision="REJECT",
        rejection_basis="insufficient_evidence",
        support_summary="Insufficient.",
        contradiction_summary="None.",
        qualification_summary="None.",
        reason="Evidence is insufficient.",
    )
    primary = MockEngine(
        [MockResponse(proposal=proposal.model_dump(mode="json"))], name="primary"
    )
    fallback = MockEngine(
        [MockResponse(proposal=proposal.model_dump(mode="json"))], name="fallback"
    )
    result = runtime.run(
        TaskType.ASSESS_CLAIM,
        AssessClaimInput(
            claim_id="C0001",
            claim_paper_evidence_ids=["CPE-C0001-P0001"],
        ),
        dependency_ids=["C0001", "CPE-C0001-P0001"],
        engines=[primary, fallback],
    )
    assert result.outcome is AttemptOutcome.VALID_SCIENTIFIC_RESULT
    assert result.transition is not None
    assert result.transition.scientific_disposition == "REJECT"
    assert result.transition.canonicalized
    assert not result.transition.downstream_eligible
    assert primary.calls == 1
    assert fallback.calls == 0
    _, current, _ = runtime.store.load_current()
    assert current.claim_assessments[0].decision.value == "REJECT"
    assert current.claim_packets == ()


