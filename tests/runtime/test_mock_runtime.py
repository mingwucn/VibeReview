def test_concurrent_tasks_allocate_canonical_ids_without_collision(tmp_path):
    initial = RepositorySnapshot(
        themes=(
            ThemeRecord(
                theme_id="T0001",
                title="Existing",
                description="existing",
                origin="human",
                parent_theme_id=None,
            ),
        ),
        candidate_claims=(
            CandidateClaim(
                claim_id="C0040",
                theme_id="T0001",
                candidate_claim="Existing claim",
                origin="human",
                origin_refs=[],
            ),
        ),
    )
    runtime = ProjectRuntime.create(
        tmp_path / "project", project_name="concurrent", initial_snapshot=initial
    )
    barrier = threading.Barrier(2)

    def response(prefix):
        return DiscoveryProposalBundle(
            themes=[],
            claims=[
                CandidateClaimProposal(
                    local_ref=f"{prefix}_{index}",
                    theme_ref="T0001",
                    candidate_claim=f"Claim {prefix} {index}",
                    origin="generated",
                    origin_refs=[],
                )
                for index in range(1, 4)
            ],
        )

    def engine(prefix):
        def synchronize(task, call_number):
            if call_number == 0:
                barrier.wait(timeout=2)

        proposal = response(prefix)
        return MockEngine(
            [MockResponse(proposal=proposal.model_dump(mode="json"))],
            name=f"mock-{prefix}",
            on_execute=synchronize,
        )

    def run(prefix):
        return runtime.run(
            TaskType.GENERATE_CANDIDATE_CLAIMS,
            GenerateCandidateClaimsInput(
                topic=f"topic-{prefix}", existing_theme_ids=["T0001"]
            ),
            dependency_ids=["T0001"],
            engines=[engine(prefix)],
        )

    with ThreadPoolExecutor(max_workers=2) as executor:
        results = list(executor.map(run, ["a", "b"]))

    allocated = {
        value
        for result in results
        for key, value in result.allocated_ids.items()
        if key.startswith(("a_", "b_"))
    }
    assert allocated == {f"C{number:04d}" for number in range(41, 47)}
    assert all(result.outcome is AttemptOutcome.VALID_SCIENTIFIC_RESULT for result in results)
    _, snapshot, _ = runtime.store.load_current()
    assert {claim.claim_id for claim in snapshot.candidate_claims} == {
        "C0040",
        *allocated,
    }
