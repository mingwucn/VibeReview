def test_hard_link_conservative_counting(tmp_path: Path):
    root = tmp_path / "exec-root"
    for d in ("output", "scratch", "home", "tmp"):
        (root / d).mkdir(parents=True)

    file1 = root / "output" / "original.bin"
    # Write 100 bytes
    file1.write_bytes(b"A" * 100)

    # Hardlink
    file2 = root / "scratch" / "hardlink.bin"
    os.link(file1, file2)

    # Two entries should count as 2 entries, and total_bytes = 200 bytes
    # Test entry count limit = 1 -> breach
    policy_entry = deterministic_test_policy().model_copy(update={"max_writable_entries": 1})
    breach_entry = scan_writable_roots(root, policy_entry)
    assert breach_entry is not None
    assert breach_entry.code == ResourceLimitCode.MAX_WRITABLE_ENTRY_COUNT

    # Test tree bytes limit = 150 -> breach because apparent size is counted twice (100 + 100 = 200 > 150)
    policy_bytes = deterministic_test_policy().model_copy(
        update={"max_writable_entries": 10, "max_writable_tree_bytes": 150}
    )
    breach_bytes = scan_writable_roots(root, policy_bytes)
    assert breach_bytes is not None
    assert breach_bytes.code == ResourceLimitCode.MAX_WRITABLE_TREE_BYTES


