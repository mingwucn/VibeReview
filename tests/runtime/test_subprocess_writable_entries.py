def test_directories_counted_towards_quota(tmp_path: Path):
    root = tmp_path / "exec-root"
    for d in ("output", "scratch", "home", "tmp"):
        (root / d).mkdir(parents=True)

    # Create 257 directories under scratch
    for i in range(257):
        (root / "scratch" / f"dir_{i:04d}").mkdir()

    policy = deterministic_test_policy().model_copy(update={"max_writable_entries": 256})
    breach = scan_writable_roots(root, policy)
    assert breach is not None
    assert breach.code == ResourceLimitCode.MAX_WRITABLE_ENTRY_COUNT
    assert "Writable entry count exceeded 256." in breach.message


