def test_mixed_entries_totaling_quota_breach(tmp_path: Path):
    root = tmp_path / "exec-root"
    for d in ("output", "scratch", "home", "tmp"):
        (root / d).mkdir(parents=True)

    # 100 regular files in output
    for i in range(100):
        (root / "output" / f"file_{i:03d}.txt").write_text("x", encoding="utf-8")

    # 100 directories in scratch
    for i in range(100):
        (root / "scratch" / f"dir_{i:03d}").mkdir()

    # 57 FIFOs in tmp
    for i in range(57):
        os.mkfifo(root / "tmp" / f"fifo_{i:03d}")

    # Total entries = 100 + 100 + 57 = 257
    policy = deterministic_test_policy().model_copy(update={"max_writable_entries": 256})
    breach = scan_writable_roots(root, policy)
    assert breach is not None
    assert breach.code == ResourceLimitCode.MAX_WRITABLE_ENTRY_COUNT


