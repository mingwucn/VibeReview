def _engine(
    name: str,
    modes: tuple[str, ...],
    *,
    payloads: dict[str, bytes] | None = None,
    stretch_monitor_interval: bool = False,
) -> SubprocessEngine:
    policy = deterministic_test_policy()
    if stretch_monitor_interval:
        # Stretch the mid-run monitor interval past the worker's lifetime so a
        # quota breach is adjudicated by the unconditional post-exit scan; the
        # process exit status is then also observed and retained, which makes
        # the simultaneously-detected failure set deterministic.
        policy = policy.model_copy(
            update={"writable_tree_scan_interval_seconds": 30.0}
        )
    return SubprocessEngine(
        worker_script=WORKER,
        modes=modes,
        proposal_payloads=dict(payloads or {}),
        name=name,
        policy=policy,
    )


def _run_discovery(
    runtime: ProjectRuntime, engines: list[SubprocessEngine]
) -> RuntimeResult:
    return runtime.run(
        TaskType.GENERATE_CANDIDATE_CLAIMS,
        GenerateCandidateClaimsInvocation(topic="precedence", existing_theme_ids=[]),
        engines=engines,
    )


def _execution_report(runtime: ProjectRuntime, record: TaskAttemptRecord) -> dict:
    agent_result = json.loads(
        (runtime.project_root / record.agent_result_path).read_text(encoding="utf-8")
    )
    return agent_result["execution_report"]


def _inventory_entry(report: dict, relative_path: str) -> dict:
    for entry in report["inventory"]:
        if entry["relative_path"] == relative_path:
            return entry
    raise AssertionError(f"execution inventory lacks {relative_path}")


def _failure_triples(record: TaskAttemptRecord) -> list[tuple]:
    return [
        (failure.code, failure.stage, failure.relative_path)
        for failure in record.detected_failures
    ]


def _attempt_dir(runtime: ProjectRuntime, record: TaskAttemptRecord) -> Path:
    return (
        runtime.project_root
        / "work"
        / "tasks"
        / record.task_id
        / "attempts"
        / record.attempt_id
    )


def _persisted_record(runtime: ProjectRuntime, record: TaskAttemptRecord) -> None:
    persisted = TaskAttemptRecord.model_validate_json(
        (_attempt_dir(runtime, record) / "attempt_record.json").read_text(
            encoding="utf-8"
        )
    )
    assert persisted == record


def _assert_failed_run_preserves_state(
    runtime: ProjectRuntime, result: RuntimeResult, generation_before: int
) -> None:
    assert result.generation is None
    assert result.transition is None
    assert runtime.store.current_generation() == generation_before


def test_bundle_tampering_with_malformed_proposal_is_workspace_integrity_failure(
    tmp_path,
):
    runtime = ProjectRuntime.create(tmp_path / "project", project_name="integrity")
    generation_before = runtime.store.current_generation()
    engine = _engine("tamper-malformed", ("tamper_instructions", "malformed_json"))
    result = _run_discovery(runtime, [engine])

    assert result.outcome is AttemptOutcome.ENGINE_WORKSPACE_INTEGRITY_FAILURE
    assert len(result.attempt_records) == 1
    record = result.attempt_records[0]
    assert record.outcome is AttemptOutcome.ENGINE_WORKSPACE_INTEGRITY_FAILURE
    assert fallback_allowed(record.outcome)
    # The runner-stage condition is retained. §6.6 selects exactly one primary
    # outcome, so the kernel format stage never adjudicates the malformed
    # proposal once workspace integrity has fired.
    assert _failure_triples(record) == [
        (
            "bundle_integrity_mismatch",
            AttemptFailureStage.WORKSPACE,
            Path("bundle"),
        ),
    ]
    assert record.format_valid is False
    assert record.schema_valid is False
    assert record.proposal_validation_valid is None
    assert record.accepted_attempt is False
    assert record.validation_errors
    _persisted_record(runtime, record)

    report = _execution_report(runtime, record)
    assert report["primary_outcome"] == AttemptOutcome.ENGINE_WORKSPACE_INTEGRITY_FAILURE
    assert report["exit_code"] == 0
    assert report["timed_out"] is False
    assert report["bundle_modified"] is True
    assert report["output_policy_violated"] is False
    assert report["resource_limit_breached"] is False
    # The co-present malformed proposal is retained as hashed inventory
    # evidence rather than as a detected failure.
    proposal = _inventory_entry(report, "output/proposal.json")
    assert proposal["file_type"] == "regular"
    assert proposal["content_hash"] == hash_bytes(MALFORMED_JSON_PAYLOAD)

    _assert_failed_run_preserves_state(runtime, result, generation_before)


