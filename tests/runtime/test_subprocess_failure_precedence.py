"""End-to-end §6.6 primary-outcome precedence through the B2 subprocess pipeline.

The deterministic fake worker (tests/helpers/fake_agent.py) composes defect
modes inside one attempt; the runner (runtime/execution.py) pre-classifies the
conditions it owns — process, resource-limit, workspace-integrity, output-tree
and proposal-file stages — through the frozen ``primary_attempt_outcome``
precedence, and the kernel adjudicates the remaining format → schema →
proposal-validation stages only when the runner reported
VALID_SCIENTIFIC_RESULT (kernel.py §6.6 handoff).

Consequences asserted here:

* runner-stage combos select exactly one primary outcome on the
  TaskAttemptRecord while every other safely detected condition is retained in
  ``detected_failures`` with its code/stage;
* a co-present kernel-stage defect (a malformed proposal next to tampering or
  unauthorized output) is never adjudicated once a higher-precedence runner
  condition fired — the malformed bytes are retained and hashed in the
  execution inventory instead of appearing in ``detected_failures``;
* kernel stages keep their own precedence (format before schema before
  proposal validation);
* a valid proposal and a valid REJECT are VALID_SCIENTIFIC_RESULT and never
  fallback-eligible;
* repeating one combo run yields an identical outcome projection.

All tests run the real subprocess machinery (TemporaryWorkspaceBackend,
TEST_ONLY); none is an external-engine test.
"""

