    assert report["primary_outcome"] == AttemptOutcome.ENGINE_RESOURCE_LIMIT_FAILURE
    assert report["exit_code"] == 3
    assert report["timed_out"] is False
    assert report["resource_limit_breached"] is True
    assert report["bundle_modified"] is False

