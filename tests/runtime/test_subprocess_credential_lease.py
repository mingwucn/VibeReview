def _engine(
    name: str,
    *,
    modes: tuple[str, ...] = ("valid",),
    credential_provider: EngineCredentialProvider | None = None,
    worker_config: dict | None = None,
) -> SubprocessEngine:
    return SubprocessEngine(
        name=name,
        worker_script=WORKER,
        modes=modes,
        credential_provider=credential_provider,
        worker_config=worker_config,
        proposal_payloads={
            "valid_proposal.json": json.dumps(VALID_PROPOSAL).encode("utf-8")
        },
    )


def _init_runtime(tmp_path: Path) -> ProjectRuntime:
    return ProjectRuntime.create(tmp_path / "project", project_name="cred-test")


def _run_task(runtime: ProjectRuntime, engine: SubprocessEngine):
    return runtime.run(
        TaskType.GENERATE_CANDIDATE_CLAIMS,
        GenerateCandidateClaimsInvocation(topic="Stress", existing_theme_ids=[]),
        engines=[engine],
    )


def test_parent_only_secret_absent_from_child_and_diagnostics(tmp_path: Path, monkeypatch):
    """Parent-only secret exists in parent environment but is absent from child (goal.md §7.6)."""
    parent_secret = "SUPER_SECRET_PARENT_VALUE_999"
    monkeypatch.setenv("VIBEREVIEW_PARENT_SECRET", parent_secret)

    engine = _engine("fake-parent-secret", modes=("parent_secret_probe", "valid"))
    runtime = _init_runtime(tmp_path)
    result = _run_task(runtime, engine)

    assert result.outcome is AttemptOutcome.VALID_SCIENTIFIC_RESULT
    record = result.attempt_records[0]
    agent_result = SubprocessAgentResult.model_validate_json(
        (runtime.project_root / record.agent_result_path).read_text(encoding="utf-8")
    )
    assert "PARENT_SECRET=<absent>" in agent_result.stdout
    assert parent_secret not in agent_result.stdout
    assert parent_secret not in agent_result.stderr


