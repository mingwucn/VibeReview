def git(repository: Path, *args: str) -> None:
    subprocess.run(
        ["git", "-C", str(repository), *args], check=True, capture_output=True
    )


def init_repository(path: Path) -> None:
    path.mkdir()
    git(path, "init", "-b", "main")
    git(path, "config", "user.name", "Synthetic Fixture")
    git(path, "config", "user.email", "fixture.invalid@example.invalid")


def test_deleted_forbidden_path_is_still_found_in_history(tmp_path: Path) -> None:
    repository = tmp_path / "repository"
    init_repository(repository)
    forbidden = repository / "reviews" / "private" / "result.md"
    forbidden.parent.mkdir(parents=True)
    forbidden.write_text("synthetic only\n", encoding="utf-8")
    git(repository, "add", ".")
    git(repository, "commit", "-m", "add excluded path")
    git(repository, "rm", "reviews/private/result.md")
    git(repository, "commit", "-m", "delete excluded path")

    violations = scan_public_boundary(repository, include_worktree=False)
    assert any("review artifacts" in item for item in violations)


