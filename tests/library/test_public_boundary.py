def test_ignored_private_file_is_not_opened_by_public_guard(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    repository = tmp_path / "repository"
    init_repository(repository)
    (repository / ".gitignore").write_text("ignored-private.txt\n", encoding="utf-8")
    (repository / "safe.txt").write_text("public fixture\n", encoding="utf-8")
    git(repository, "add", ".")
    git(repository, "commit", "-m", "safe fixture")
    ignored = repository / "ignored-private.txt"
    ignored.write_text("private marker\n", encoding="utf-8")
    denylist = tmp_path / "denylist"
    denylist.write_text("text:private marker\n", encoding="utf-8")
    original = public_guard.read_contained_regular_file

    def reject_ignored(root: Path, relative_path: str, **kwargs):
        assert relative_path != "ignored-private.txt"
        return original(root, relative_path, **kwargs)

    monkeypatch.setattr(public_guard, "read_contained_regular_file", reject_ignored)
    assert scan_public_boundary(repository, denylist_path=denylist) == []


def test_private_library_inputs_and_generation_resources_are_ignored() -> None:
    repository = Path(__file__).resolve().parents[2]
    private_paths = [
        "external/source/paper.md",
        "configs/libraries/operator.toml",
        "reviews/example/input/selection.json",
        (
            "reviews/example/state/generations/000001/auxiliary/"
            "library/objects/sha256/example/raw.md"
        ),
    ]
    for path in private_paths:
        result = subprocess.run(
            ["git", "-C", str(repository), "check-ignore", "--no-index", "-q", path]
        )
        assert result.returncode == 0, path


@pytest.mark.parametrize(
    "private_path",
    [
        "local-corpora/source/paper.md",
        "state/generations/000001/repository.json",
    ],
)
def test_force_added_private_runtime_roots_are_rejected(
    private_path: str, tmp_path: Path
) -> None:
    repository = tmp_path / "repository"
    init_repository(repository)
    (repository / ".gitignore").write_text(
        "/local-corpora/\n/state/\n", encoding="utf-8"
    )
    target = repository / private_path
    target.parent.mkdir(parents=True)
    target.write_text("synthetic fixture\n", encoding="utf-8")
    git(repository, "add", ".gitignore")
    subprocess.run(
        ["git", "-C", str(repository), "add", "-f", private_path],
        check=True,
        capture_output=True,
    )
    git(repository, "commit", "-m", "force-added private path")
    assert any(
        "forbidden path prefix" in item
        for item in scan_public_boundary(repository, include_worktree=False)
    )
