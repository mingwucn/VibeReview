"""Programmatic sandbox conformance suite and report contract (goal.md §6.1).

The report is generated by actually executing every required case through the
real :class:`SubprocessEngine` + :class:`BubblewrapExecutionBackend` path
against a throwaway review project in a fresh temporary directory — never by
trusting pytest results. The dedicated :mod:`vibereview.runtime.conformance_worker`
is the only worker; test helpers are never imported by shipped runtime code.

Case ids equal the pytest conformance test names so the report suite and the
pytest suite cannot drift apart.
"""

